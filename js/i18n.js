(function () {
  "use strict";

  var LANG_KEY = "cb-lang";
  var originals = new Map();

  function getStored() {
    try { return localStorage.getItem(LANG_KEY); } catch (e) { return null; }
  }
  function setStored(lang) {
    try { localStorage.setItem(LANG_KEY, lang); } catch (e) {}
  }

  function snapshot() {
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      if (!originals.has(el)) originals.set(el, el.textContent);
    });
  }

  function apply(lang) {
    var html = document.documentElement;
    html.lang = lang;
    html.dir = lang === "ar" ? "rtl" : "ltr";

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (lang === "ar" && window.CB_I18N && Object.prototype.hasOwnProperty.call(window.CB_I18N, key)) {
        el.textContent = window.CB_I18N[key];
      } else {
        el.textContent = originals.get(el);
      }
    });

    document.querySelectorAll(".lang__opt").forEach(function (btn) {
      btn.setAttribute("aria-current", btn.dataset.lang === lang ? "true" : "false");
    });
    document.querySelectorAll(".lang__code").forEach(function (code) {
      code.textContent = lang.toUpperCase();
    });

    setStored(lang);
  }

  function closeAll() {
    document.querySelectorAll(".lang.is-open").forEach(function (wrap) {
      wrap.classList.remove("is-open");
      var btn = wrap.querySelector(".lang__btn");
      if (btn) btn.setAttribute("aria-expanded", "false");
    });
  }

  function init() {
    snapshot();
    apply(getStored() || "en");

    document.querySelectorAll("[data-lang-switch]").forEach(function (wrap) {
      var btn = wrap.querySelector(".lang__btn");
      if (!btn) return;

      btn.addEventListener("click", function (e) {
        e.stopPropagation();
        var open = !wrap.classList.contains("is-open");
        closeAll();
        wrap.classList.toggle("is-open", open);
        btn.setAttribute("aria-expanded", String(open));
      });

      wrap.querySelectorAll(".lang__opt").forEach(function (opt) {
        opt.addEventListener("click", function () {
          apply(opt.dataset.lang);
          closeAll();
        });
      });
    });

    document.addEventListener("click", closeAll);
    document.addEventListener("keydown", function (e) {
      if (e.key === "Escape") closeAll();
    });
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
})();
